def parse_args(argv: Optional[list] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="S-45 DREAMPlace floorplan driver — TT-Shuttle Squeeze v7",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=f"Anchor: {PROJECT_ANCHOR}",
    )
    parser.add_argument(
        "--def",
        dest="input_def",
        default="input.def",
        help="Path to input DEF file (default: input.def)",
    )
    parser.add_argument(
        "--config",
        default=str(Path(__file__).parent / "config.json"),
        help="Path to DREAMPlace config JSON (default: config.json next to script)",
    )
    parser.add_argument(
        "--output-def",
        default="optimized.def",
        help="Output DEF path (default: optimized.def)",
    )
    parser.add_argument(
        "--report",
        default="placement_report.json",
        help="Output JSON report path (default: placement_report.json)",
    )
    parser.add_argument(
        "--rl-steps",
        type=int,
        default=10,
        help="Number of RL refinement steps (default: 10)",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=SEED,
        help=f"Random seed (default: {SEED})",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Skip all tool invocations; emit stub outputs only",
    )
    return parser.parse_args(argv)


def main(argv: Optional[list] = None) -> int:
    args = parse_args(argv)

    log.info("=== S-45 DREAMPlace floorplan driver (%s) ===", VERSION)
    log.info("Anchor: %s", PROJECT_ANCHOR)
    log.info("R5 honesty: projection until chip-in-hand 2026-12-16")

    if not _DREAMPLACE_AVAILABLE:
        log.warning(
            "CI_SKIP_DREAMPLACE: DREAMPlace binary not found.  "
            "Producing stub outputs.  "
            "Install DREAMPlace (https://github.com/limbo018/DREAMPlace) "
            "to enable real GPU/CPU placement."
        )

    # Load config
    config_path = Path(args.config)
    if config_path.exists():
        with config_path.open("r", encoding="utf-8") as fh:
            config = json.load(fh)
        log.info("Config loaded from %s", config_path)
    else:
        log.warning("Config not found at %s — using empty config", config_path)
        config = {}

    # Override seed from CLI
    config["random_seed"] = args.seed

    t_start = time.monotonic()

    # 1. Load DEF
    input_path = Path(args.input_def)
    design = load_def(input_path)

    # 2. Run DREAMPlace
    if not args.dry_run:
        design = run_dreamplace(design, config, seed=args.seed)
    else:
        log.info("--dry-run: skipping DREAMPlace invocation")
        design.setdefault("metrics", {"hpwl": 9800.0, "wns_ps": 0, "utilization": 0.70})

    # 3. RL refinement
    rl = RLRefinement(config, seed=args.seed)
    design = rl.run_episode(design, steps=args.rl_steps)

    # 4. Write outputs
    output_def = Path(args.output_def)
    write_def(design, output_def, input_path)

    report_path = Path(args.report)
    elapsed = time.monotonic() - t_start
    write_report(design, report_path, elapsed, config, seed=args.seed)

    # 5. Exit code based on G-45
    wns = design.get("metrics", {}).get("wns_ps", 0)
    if wns >= WNS_TARGET_PS:
        log.info("SUCCESS: G-45 satisfied (WNS=%d ps)", wns)
        return 0
    else:
        if _DREAMPLACE_AVAILABLE:
            log.error("FAIL: G-45 not satisfied (WNS=%d ps, need >=%d ps)", wns, WNS_TARGET_PS)
            return 1
        else:
            log.warning(
                "SKIPPED: DREAMPlace not installed — G-45 gate deferred to operator env. "
                "WNS stub value: %d ps",
                wns,
            )
            return 0  # allowed-failure in CI when DREAMPlace absent


if __name__ == "__main__":
    sys.exit(main())
