def load_def(path: Path) -> Dict[str, Any]:
    """Load a LEF/DEF file and return a minimal design dict.

    In production this calls into OpenDB.  In CI without the full
    toolchain we parse only the COMPONENTS section header for gate count.
    """
    log.info("Loading DEF: %s", path)
    design: Dict[str, Any] = {
        "path": str(path),
        "components": [],
        "nets": [],
        "rows": [],
        "die_area": None,
    }

    if not path.exists():
        log.warning("DEF file not found: %s — using empty stub design", path)
        return design

    component_count: int = 0
    with path.open("r", encoding="utf-8") as fh:
        for line in fh:
            stripped = line.strip()
            if stripped.startswith("COMPONENTS"):
                parts = stripped.split()
                if len(parts) >= 2 and parts[1].isdigit():
                    component_count = int(parts[1])
            if stripped.startswith("DIEAREA"):
                design["die_area"] = stripped
    design["component_count"] = component_count
    log.info("DEF parsed: %d components", component_count)
    return design


def write_def(design: Dict[str, Any], output_path: Path, source_path: Path) -> None:
    """Write optimised placement back to a DEF file.

    In production this calls OpenDB writer.  In CI stub mode we copy the
    source DEF and append a header comment documenting the optimisation run.
    """
    log.info("Writing optimised DEF → %s", output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    header_lines = [
        f"# DREAMPlace-optimised DEF — seed={SEED}\n",
        f"# Anchor: {PROJECT_ANCHOR}\n",
        f"# Generated by {VERSION}\n",
        "# NOTE: stub output (DREAMPlace not installed)\n\n",
    ]

    if source_path.exists():
        source_content = source_path.read_text(encoding="utf-8")
    else:
        source_content = "# (source DEF not found — stub placeholder)\n"

    output_path.write_text("".join(header_lines) + source_content, encoding="utf-8")


# ---------------------------------------------------------------------------
# RL refinement action space
# ---------------------------------------------------------------------------

class RLRefinement:
    """Lightweight RL wrapper for AlphaChip-style policy refinement.

    Action space (per config.json):
      - pe_swap:    swap two Processing-Element columns
      - io_permute: rotate IO pad assignment ring
      - pll_rotate: rotate PLL placement quadrant

    In CI dry-run mode, this logs the action space and returns mock metrics.
    """

    ACTION_NAMES = ("pe_swap", "io_permute", "pll_rotate")

    def __init__(self, config: Dict[str, Any], seed: int = SEED) -> None:
        self.config = config
        self.seed = seed
        self._rng_state: int = seed
        log.info(
            "RLRefinement initialised (seed=%d, actions=%s)",
            seed,
            self.ACTION_NAMES,
        )

    def _pseudo_random(self) -> float:
        """Deterministic LCG for reproducibility in dry-run mode."""
        # LCG parameters (Knuth)
        self._rng_state = (self._rng_state + 6364136223846793005) % (2 ** 64)
        return (self._rng_state >> 33) / (2 ** 31)

    def select_action(self, state: Dict[str, Any]) -> str:
        """Select an action from the action space based on current state."""
        idx = int(self._pseudo_random() * len(self.ACTION_NAMES))
        action = self.ACTION_NAMES[idx]
        log.debug("RL selected action: %s (state keys: %s)", action, list(state.keys()))
        return action

    def apply_action(
        self, design: Dict[str, Any], action: str
    ) -> Dict[str, Any]:
        """Apply an RL action to the design and return updated metrics."""
        log.info("Applying RL action: %s", action)
        metrics = design.get("metrics", {}).copy()

        if action == "pe_swap":
            # Simulate wire-length improvement from PE column swap
            prev_hpwl = metrics.get("hpwl", 1000.0)
            metrics["hpwl"] = prev_hpwl - (prev_hpwl * 0.02)  # 2% improvement
        elif action == "io_permute":
            prev_hpwl = metrics.get("hpwl", 1000.0)
            metrics["hpwl"] = prev_hpwl - (prev_hpwl * 0.015)
        elif action == "pll_rotate":
            prev_wns = metrics.get("wns_ps", 0)
            metrics["wns_ps"] = prev_wns + 50  # +50 ps per PLL rotate
        else:
            log.warning("Unknown action: %s — skipping", action)

        design["metrics"] = metrics
        return design

    def run_episode(
        self, design: Dict[str, Any], steps: int = 10
    ) -> Dict[str, Any]:
        """Run one RL episode for the given number of steps."""
        log.info("Starting RL episode (steps=%d, seed=%d)", steps, self.seed)
        for step in range(steps):
            action = self.select_action(design)
            design = self.apply_action(design, action)
            log.debug("Step %d/%d — action=%s metrics=%s", step + 1, steps, action, design.get("metrics"))
        log.info("RL episode complete — final metrics: %s", design.get("metrics"))
        return design


